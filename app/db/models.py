"""Schema, identical on every shard. Shards differ only in WHICH accounts they hold."""
from __future__ import annotations

import enum
from datetime import datetime, timezone

from sqlalchemy import (
    BigInteger, CheckConstraint, Column, DateTime, Enum, Index, Integer, String,
    UniqueConstraint,
)
from sqlalchemy.orm import declarative_base

Base = declarative_base()


def _now() -> datetime:
    return datetime.now(timezone.utc)


class TransactionState(str, enum.Enum):
    PROCESSING = "PROCESSING"  # cross-shard: debited, credit still in flight
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"          # credit impossible; debit was refunded


# Single source of truth for legal lifecycle moves (see core/state_machine.py).
VALID_TRANSITIONS = {
    TransactionState.PROCESSING: {TransactionState.COMPLETED, TransactionState.FAILED},
    TransactionState.COMPLETED: set(),
    TransactionState.FAILED: set(),
}


class Account(Base):
    __tablename__ = "accounts"
    __table_args__ = (
        # Last line of defence: even a buggy code path cannot overdraw.
        CheckConstraint("balance_minor >= 0", name="ck_accounts_balance_non_negative"),
    )

    id = Column(String, primary_key=True)  # also the shard key; generated by the API
    owner_name = Column(String, nullable=False)
    balance_minor = Column(BigInteger, nullable=False, default=0)
    currency = Column(String(3), nullable=False, default="INR")
    version = Column(Integer, nullable=False, default=0)  # bumped on every balance change
    created_at = Column(DateTime(timezone=True), default=_now)


class Transaction(Base):
    """Lives on the DEBIT account's shard. id is '<debit_shard>-<uuid>' so any
    transaction can be located from its id alone."""

    __tablename__ = "transactions"
    __table_args__ = (
        # Makes idempotency atomic at the database level (see DECISIONS.md #3).
        UniqueConstraint("idempotency_key", name="uq_transactions_idempotency_key"),
    )

    id = Column(String, primary_key=True)
    idempotency_key = Column(String, nullable=False)
    request_fingerprint = Column(String, nullable=False)
    debit_account_id = Column(String, nullable=False)
    credit_account_id = Column(String, nullable=False)  # may be on another shard
    credit_shard_index = Column(Integer, nullable=False)
    amount_minor = Column(BigInteger, nullable=False)
    currency = Column(String(3), nullable=False)
    state = Column(Enum(TransactionState), nullable=False)
    failure_reason = Column(String, nullable=True)
    created_at = Column(DateTime(timezone=True), default=_now)
    updated_at = Column(DateTime(timezone=True), default=_now, onupdate=_now)


class OutboxEvent(Base):
    """Transactional outbox: written in the same DB transaction as the business
    change, relayed to the broker later. Avoids the dual-write problem."""

    __tablename__ = "outbox_events"
    __table_args__ = (Index("ix_outbox_unpublished", "published", "created_at"),)

    id = Column(String, primary_key=True)
    aggregate_id = Column(String, nullable=False)  # transaction id (Kafka partition key)
    event_type = Column(String, nullable=False)
    payload_json = Column(String, nullable=False)
    published = Column(Integer, nullable=False, default=0)
    created_at = Column(DateTime(timezone=True), default=_now)
    published_at = Column(DateTime(timezone=True), nullable=True)


class ProcessedEvent(Base):
    """Consumer-side dedup: turns at-least-once delivery into effectively-once."""

    __tablename__ = "processed_events"

    event_id = Column(String, primary_key=True)
    processed_at = Column(DateTime(timezone=True), default=_now)
